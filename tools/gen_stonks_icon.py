#!/usr/bin/env python3
"""
Generates main/stonks_icon.c: the "diamond hands" icon for the St0nks app
(a gem held up by two raised hands), as LVGL v8 LV_IMG_CF_TRUE_COLOR_ALPHA
images for RGB565 without byte swap.

The gem and hands are Twemoji graphics (Twitter, CC-BY 4.0,
https://github.com/twitter/twemoji), from the Fedora twitter-twemoji-fonts
package.

Run from the project root:
    python3 -I tools/gen_stonks_icon.py [preview.png]
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_game_images import to_c  # noqa: E402

FONT = "/usr/share/fonts/twemoji/Twemoji.ttf"
FONT_PX = 61        # the bitmap font only loads at its own size
WORK = 256          # compose big, then scale down


def emoji(ch):
    font = ImageFont.truetype(FONT, FONT_PX)
    im = Image.new("RGBA", (FONT_PX * 2, FONT_PX * 2), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((4, 4), ch, font=font, embedded_color=True)
    return im.crop(im.getbbox())


def fit(img, w):
    h = round(img.height * w / img.width)
    return img.resize((w, h), Image.LANCZOS)


def make_icon(size):
    hands = emoji("\U0001F64C")
    # Cut off the little "raise" lines above the fingertips.
    hands = hands.crop((0, hands.height * 18 // 100, hands.width, hands.height))
    hands = fit(hands.crop(hands.getbbox()), WORK)
    gem = fit(emoji("\U0001F48E"), WORK * 52 // 100)
    canvas = Image.new("RGBA", (WORK, WORK), (0, 0, 0, 0))
    canvas.alpha_composite(hands, (0, WORK - hands.height))
    # The gem sits between the raised palms.
    canvas.alpha_composite(gem, ((WORK - gem.width) // 2, 2))
    return canvas.resize((size, size), Image.LANCZOS)


def main():
    images = [("img_stonks_icon", make_icon(64)), ("img_stonks_small", make_icon(36))]
    out = ["/* Generated by tools/gen_stonks_icon.py; do not edit by hand.",
           " * Graphics: Twemoji by Twitter, CC-BY 4.0. */",
           '#include "lvgl.h"', "",
           "#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 0",
           '#error "stonks_icon.c was generated for RGB565 without byte swap"',
           "#endif", ""]
    for name, img in images:
        out.append(to_c(name, img))
    with open("main/stonks_icon.c", "w") as f:
        f.write("\n".join(out))
    print("wrote main/stonks_icon.c")

    if len(sys.argv) > 1:
        prev = Image.new("RGBA", (200, 100), (46, 125, 50, 255))
        prev.alpha_composite(images[0][1], (10, 18))
        prev.alpha_composite(images[1][1], (110, 32))
        prev = prev.resize((prev.width * 3, prev.height * 3), Image.NEAREST)
        prev.save(sys.argv[1])
        print("wrote", sys.argv[1])


if __name__ == "__main__":
    main()

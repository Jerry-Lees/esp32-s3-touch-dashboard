#!/usr/bin/env python3
"""
Generates main/app_symbols.c: the table of firmware functions and data that
SD card apps may use (the ELF loader resolves an app's undefined symbols
against it). Contents:

  - every global symbol of the compiled LVGL library (lv_*, _lv_*),
  - the C library / math / compiler helpers in EXTRA below,
  - the dashboard API (dash_*, sdk/dashboard_sdk/include/dashboard_app.h).

Run after a firmware build whenever LVGL's configuration changes (new
widgets or fonts), then build again:

  python3 tools/gen_app_symbols.py
"""
import glob
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "build/esp-idf/lvgl__lvgl/liblvgl__lvgl.a")
OUT = os.path.join(ROOT, "main/app_symbols.c")

# Besides what the ELF loader already provides (malloc, memcpy, printf, ...).
EXTRA = """
snprintf vsnprintf sprintf sscanf strncpy strncmp strcpy strcat strstr strdup strndup
memmove memcmp memchr strcasecmp strncasecmp strlcpy strlcat strtoul strtoll atoi atof
abs labs qsort bsearch rand srand toupper tolower isalpha isdigit isspace
time localtime_r gmtime_r mktime gettimeofday difftime
sinf cosf tanf asinf acosf atanf atan2f sqrtf powf expf logf log10f floorf ceilf roundf
fmodf fabsf fminf fmaxf lroundf hypotf
sin cos tan asin acos atan atan2 sqrt pow exp log log10 floor ceil round fmod fabs
__adddf3 __subdf3 __muldf3 __divdf3 __negdf2 __eqdf2 __nedf2 __ltdf2 __ledf2 __gtdf2
__gedf2 __unorddf2 __floatsidf __floatunsidf __floatdidf __fixdfsi __fixunsdfsi __fixdfdi
__extendsfdf2 __truncdfsf2 __divsf3 __floatdisf __floatundisf __fixsfdi __fixunssfdi
__divdi3 __udivdi3 __moddi3 __umoddi3 __ashldi3 __ashrdi3 __lshrdi3
dash_app_register dash_toast dash_time_is_set dash_clock_24h dash_alloc dash_free
dash_now_ms
""".split()


def main():
    nm = glob.glob(os.path.expanduser(
        "~/.espressif/tools/xtensa-esp-elf/*/xtensa-esp-elf/bin/xtensa-esp32s3-elf-nm"))[0]
    out = subprocess.run([nm, "-g", "--defined-only", LIB], capture_output=True,
                         text=True, check=True).stdout
    # Skip LVGL's demos and examples (and their images): exporting them would
    # pull them into the firmware.
    lv, skip = set(), False
    for line in out.splitlines():
        if line.endswith(":"):
            obj = line[:-1]
            skip = "demo" in obj or "example" in obj or obj.startswith("img_")
            continue
        f = line.split()
        if (not skip and len(f) == 3 and f[1] in "TDRB" and f[2].startswith(("lv_", "_lv_"))
                and "demo" not in f[2] and "example" not in f[2]):
            lv.add(f[2])
    lv = sorted(lv)
    names = lv + EXTRA
    with open(OUT, "w") as f:
        f.write("/* Generated by tools/gen_app_symbols.py: don't edit by hand.\n"
                " * What SD card apps may call (resolved by the ELF loader). */\n"
                "#include <stddef.h>\n\n#include \"private/elf_symbol.h\"\n\n"
                "#pragma GCC diagnostic push\n"
                "#pragma GCC diagnostic ignored \"-Wbuiltin-declaration-mismatch\"\n")
        for n in names:
            f.write(f"extern char {n};\n")
        f.write("#pragma GCC diagnostic pop\n\n"
                "const struct esp_elfsym g_dash_app_symbols[] = {\n")
        for n in names:
            f.write(f"    ESP_ELFSYM_EXPORT({n}),\n")
        f.write("    ESP_ELFSYM_END\n};\n")
    print(f"{OUT}: {len(lv)} LVGL symbols + {len(EXTRA)} others")


if __name__ == "__main__":
    main()
